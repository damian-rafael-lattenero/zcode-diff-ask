// Regenerate diff-ask/ui/src/lang-svgs.generated.js from src/icons/*.svg.
//
// The panel ships ONE self-contained HTML bundle, so the icons ride as inline
// SVG strings (no file loads, no data-URI padding). Run after adding or
// replacing an icon: `npm run icons`. Deterministic output (sorted keys) so a
// no-op regeneration produces no diff.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ICONS = path.join(HERE, "..", "diff-ask", "ui", "src", "icons");
const OUT = path.join(HERE, "..", "diff-ask", "ui", "src", "lang-svgs.generated.js");

/** Strip the XML prolog/comments, collapse whitespace and SCOPE every id.
 *  Devicon files reuse ids like `id="a"` for gradients; inline SVGs share one
 *  document, so ids are prefixed per icon (and every url(#…)/href(#…) with
 *  them) — otherwise the first icon's gradient would leak into the rest. */
function compact(svg, key) {
  const p = `da-${key}-`;
  return svg
    .replace(/<\?xml[\s\S]*?\?>/g, "")
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/\bid="([^"]+)"/g, (_m, id) => `id="${p}${id}"`)
    .replace(/url\(#([^)]+)\)/g, (_m, id) => `url(#${p}${id})`)
    .replace(/((?:xlink:)?href)="#([^"]+)"/g, (_m, attr, id) => `${attr}="#${p}${id}"`)
    .replace(/>\s+</g, "><")
    .trim();
}

/** Relative luminance of #rrggbb (0 dark … 1 light). */
function lum(hex) {
  const n = parseInt(hex.slice(1), 16);
  const [r, g, b] = [(n >> 16) & 255, (n >> 8) & 255, n & 255].map((v) => {
    const s = v / 255;
    return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

/**
 * How an icon must be treated on a DARK theme:
 *  - `mono`: the SVG declares no color at all (devicon markdown is pure black
 *    paths) → inject `fill="currentColor"` so the panel's text color rules
 *    (black on light, white on dark);
 *  - `dark`: the icon's own colors are dark (avg luminance < 0.35, e.g.
 *    Erlang's dark red, Gradle's #02303a, Astro's black tile) → the dark theme
 *    lifts it with a brightness filter.
 */
function iconTraits(svg) {
  // Paint colors ONLY (fill/stop-color attributes and style fill:), never
  // metadata like `color="#000"` — devicon's markdown carries that attr but
  // paints nothing, so it must be treated as a glyph that inherits.
  const raw = [
    ...[...svg.matchAll(/(?:fill|stop-color)=["'](#[0-9a-fA-F]{3,6})["']/g)].map((m) => m[1]),
    ...[...svg.matchAll(/\bfill:\s*(#[0-9a-fA-F]{3,6})/g)].map((m) => m[1]),
  ];
  const colors = raw.map((h) => (h.length === 4 ? `#${h.slice(1).split("").map((c) => c + c).join("")}` : h));
  const hasPaint = colors.length > 0 || /url\(#/.test(svg) || /\bfill="(?!none|currentColor)/.test(svg);
  if (!colors.length) {
    if (hasPaint) return { traits: {}, svg }; // gradients/currentColor only: as authored
    // no paint information: make it inherit (black glyph → white on dark)
    return { traits: { mono: true }, svg: svg.replace(/<svg\b/, '<svg fill="currentColor"') };
  }
  // The icon is "dark" only when even its BRIGHTEST paint color is dark (a
  // dark monochrome mark): a colorful icon with a dark shadow is still visible.
  const brightest = Math.max(...colors.map(lum));
  return { traits: brightest < 0.25 ? { dark: true } : {}, svg };
}

const files = fs
  .readdirSync(ICONS)
  .filter((n) => n.endsWith(".svg"))
  .sort();
const entries = [];
const meta = {};
for (const f of files) {
  const key = f.slice(0, -4);
  let svg = compact(fs.readFileSync(path.join(ICONS, f), "utf8"), key);
  if (!/<svg[\s>]/.test(svg)) {
    console.error(`skip ${f}: not an svg`);
    continue;
  }
  const t = iconTraits(svg);
  svg = t.svg;
  if (Object.keys(t.traits).length) meta[key] = t.traits;
  entries.push([key, svg]);
}
const body = entries.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");
const metaBody = Object.entries(meta)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
  .join("\n");
const out = `// GENERATED by scripts/gen-lang-svgs.mjs from src/icons/*.svg — do not edit.
// Regenerate with \`npm run icons\`. Sources/licenses: src/icons/NOTICE.md.
export const LANG_SVGS = {
${body}
};
/** Per-icon treatment: mono = inherits currentColor; dark = needs a lift on dark themes. */
export const LANG_ICON_META = {
${metaBody}
};
`;
fs.writeFileSync(OUT, out);
console.log(`lang-svgs.generated.js — ${entries.length} icons (${Object.keys(meta).length} with traits), ${(Buffer.byteLength(out) / 1024).toFixed(1)} KiB`);
console.log("traits:", JSON.stringify(meta));
